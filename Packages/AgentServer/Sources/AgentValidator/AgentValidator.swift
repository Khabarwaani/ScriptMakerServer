import Foundation
import AgentCore

@main
struct AgentValidatorTool {
    static func main() {
        let args = CommandLine.arguments
        guard args.count >= 2 else {
            fputs("Usage: AgentValidator <agents-directory> [output-metadata-json] [output-swift]\n", stderr)
            exit(1)
        }

        let agentsDirPath = args[1]
        let outputJSONPath = args.count > 2 ? args[2] : nil
        let outputSwiftPath = args.count > 3 ? args[3] : nil

        let agentsDir = URL(fileURLWithPath: agentsDirPath).standardizedFileURL

        do {
            let metadataList = try AgentPackageValidator.validateAll(in: agentsDir)

            let encoder = JSONEncoder()
            encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
            let jsonData = try encoder.encode(metadataList)

            if let outputJSONPath = outputJSONPath {
                let jsonURL = URL(fileURLWithPath: outputJSONPath)
                try FileManager.default.createDirectory(at: jsonURL.deletingLastPathComponent(), withIntermediateDirectories: true)
                try jsonData.write(to: jsonURL)
            }

            if let outputSwiftPath = outputSwiftPath {
                let jsonString = String(data: jsonData, encoding: .utf8) ?? "[]"
                // Escape backslashes and double quotes if needed, or use raw string syntax
                let swiftCode = """
                // Generated by AgentValidator. Do not edit directly.
                import Foundation
                import AgentCore

                public enum GeneratedAgentValidationCatalog {
                    public static let metadataJSON: String = #\"\"\"
                \(jsonString)
                \"\"\"#

                    public static let metadata: [AgentValidationMetadata] = {
                        guard let data = metadataJSON.data(using: .utf8) else { return [] }
                        return (try? JSONDecoder().decode([AgentValidationMetadata].self, from: data)) ?? []
                    }()
                }
                """
                let swiftURL = URL(fileURLWithPath: outputSwiftPath)
                try FileManager.default.createDirectory(at: swiftURL.deletingLastPathComponent(), withIntermediateDirectories: true)
                try swiftCode.write(to: swiftURL, atomically: true, encoding: .utf8)
            }

            // Print summary
            print("Successfully validated \(metadataList.count) agent package(s).")
        } catch let err as AgentPackageValidator.ValidationError {
            fputs("\(err.description)\n", stderr)
            exit(1)
        } catch {
            fputs("error: Agent validation failed: \(error.localizedDescription)\n", stderr)
            exit(1)
        }
    }
}
